export const LANGS = ["uz", "tg", "ru"] as const;
export type Lang = (typeof LANGS)[number];

/** Ma'lumotlar bazasidagi ko'p tilli matn (Prisma Json maydonlari shu shaklda) */
export type Localized = Record<Lang, string>;
export type LocalizedList = Record<Lang, string[]>;

export const LANG_LABELS: Record<Lang, string> = {
  uz: "O'zbekcha",
  tg: "Тоҷикӣ",
  ru: "Русский",
};

export const isLang = (v: unknown): v is Lang => typeof v === "string" && (LANGS as readonly string[]).includes(v);

/** Ko'p tilli qiymatdan kerakli tilni oladi; yo'q bo'lsa o'zbekchaga qaytadi */
export function L(value: Partial<Localized> | string | null | undefined, lang: Lang): string {
  if (value == null) return "";
  if (typeof value === "string") return value;
  return value[lang] || value.uz || "";
}

export function LL(value: Partial<LocalizedList> | undefined, lang: Lang): string[] {
  if (!value) return [];
  return value[lang] ?? value.uz ?? [];
}

/** Bir xil matnni uchala tilga qo'yadi (formula, raqam kabi tarjimasiz matnlar uchun) */
export const same = (s: string): Localized => ({ uz: s, tg: s, ru: s });

